#!/usr/bin/env python3
"""
==============================================================================
 KORVUS VAULT WRITER  ·  korvus_intel.db -> Obsidian (blackcrown-brain/intel/)
==============================================================================
 Renders the Intel data as Obsidian notes plus machine-readable JSONL, then
 commits and pushes ONLY the intel/ folder of the blackcrown-brain repo.
 Obsidian Git on the PC (basePath BlackCrown-Brains, auto-pull every 5 min)
 brings it into the vault; the BlackCrown agents read it from the same repo.

 It never touches the agents' folders (bard, corvid, herald, regent, steward,
 theme). It keeps its own clone on the server, pulls with rebase before every
 push, and only commits when something actually changed.

 SETUP (.env on the Korvus server)
   VAULT_REPO_URL     https://github.com/Vxmpira/blackcrown-brain.git
   VAULT_GIT_TOKEN    fine-grained GitHub token: blackcrown-brain only,
                      Contents read+write. Sent as an auth header, never
                      written into the clone's config or the logs.
   VAULT_SUBDIR       default "intel"
   VAULT_SYNC_MINUTES default 10
   VAULT_DIR          default <repo>/vault_clone   (gitignored)

 CLI
   python korvus_vault.py --render-only   write notes into VAULT_DIR, no git
   python korvus_vault.py                 render + commit + push once
==============================================================================
"""
import os
import json
import base64
import argparse
import subprocess
import datetime as dt

import korvus_intel as intel

_env, _num = intel._env, intel._num

REPO_URL     = _env("VAULT_REPO_URL", "https://github.com/Vxmpira/blackcrown-brain.git")
TOKEN        = _env("VAULT_GIT_TOKEN")
SUBDIR       = _env("VAULT_SUBDIR", "intel").strip("/")
SYNC_MINUTES = max(2, int(_num("VAULT_SYNC_MINUTES", 10)))
VAULT_DIR    = _env("VAULT_DIR", os.path.join(intel.HERE, "vault_clone"))
AUTHOR       = _env("VAULT_GIT_AUTHOR", "Korvus Intel <intel@korvus.industries>")
FILING_DAYS  = 7      # daily filing notes re-rendered for the last week
TICKER_DAYS  = 90     # ticker notes cover the last 90 days
EXPORT_DAYS  = 180    # JSONL export window


# ----------------------------------------------------------------------------
# formatting helpers
# ----------------------------------------------------------------------------
def _et(iso: str, fmt: str = "%Y-%m-%d %I:%M:%S %p") -> str:
    if not iso:
        return ""
    try:
        from zoneinfo import ZoneInfo
        return dt.datetime.fromisoformat(iso).astimezone(ZoneInfo("America/New_York")).strftime(fmt)
    except Exception:
        return iso


def _et_date(iso: str) -> str:
    return _et(iso, "%Y-%m-%d")


def _cell(t) -> str:
    return str(t if t is not None else "").replace("|", "/").replace("\n", " ").strip()


def _fm(**kv) -> str:
    lines = ["---"]
    for k, v in kv.items():
        if isinstance(v, list):
            lines.append(f"{k}: [{', '.join(str(x) for x in v)}]")
        else:
            lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def _tl(sym: str) -> str:
    """Full-path ticker link, so V or MA never resolve to some other vault note."""
    return f"[[{SUBDIR}/Tickers/{sym}|{sym}]]"


GEN = "> Generated by Korvus Intel. Do not edit by hand; the next sync overwrites this note.\n"


# ----------------------------------------------------------------------------
# render (pure: DB -> {relative_path: text})
# ----------------------------------------------------------------------------
def render(now: dt.datetime = None) -> dict:
    import korvus_paperbot as bot
    now = now or intel.utcnow()
    conn = intel.db()
    universe = [dict(r) for r in conn.execute("SELECT * FROM universe ORDER BY symbol")]
    since_f = (now - dt.timedelta(days=EXPORT_DAYS)).isoformat()
    filings = [dict(r) for r in conn.execute(
        "SELECT * FROM filings WHERE seen_utc >= ? ORDER BY seen_utc DESC", (since_f,))]
    trades = [dict(r) for r in conn.execute("SELECT * FROM trades ORDER BY entry_utc DESC")]
    conn.close()
    sb = bot.scoreboard()
    files = {}
    # Stamp notes with the time the DATA last changed, not the render time,
    # so an idle sync produces no diff and no commit in the brain repo.
    marks = [f["seen_utc"] for f in filings] + [u["asof"] for u in universe if u.get("asof")]
    for t in trades:
        marks += [t["entry_utc"]] + ([t["exit_utc"]] if t.get("exit_utc") else [])
    data_asof = max(marks) if marks else ""
    stamp = (_et(data_asof) + " ET") if data_asof else "no data yet"

    # ---- README: the contract for agents ----
    files["README.md"] = _fm(type="intel-index", updated=_et_date(data_asof) or "n/a", tags=["korvus-intel"]) + f"""
# Korvus Intel

A separate data ecosystem fed by the Korvus web crawler on the Korvus server. It watches
US stocks trading near $100 (${intel.PRICE_MIN:.0f} to ${intel.PRICE_MAX:.0f}, under
${intel.MCAP_MAX/1e9:.0f}B market cap), reads their SEC filings straight from EDGAR the
moment they are accepted, scores each one for the stock, and runs a **paper-only** trading
bot on those catalysts.

{GEN}
Data as of: {stamp}

## Where things are
- [[{SUBDIR}/Universe|Universe]]: today's stock list with price, market cap, volume, sector
- `Filings/YYYY-MM-DD.md`: every filing captured that day, with the Korvus read
- `Tickers/SYMBOL.md`: per-stock history of filings and paper trades
- [[{SUBDIR}/Bot/Strategy|Strategy]] and [[{SUBDIR}/Bot/Scoreboard|Scoreboard]] in `Bot/`, plus monthly ledgers in `Bot/Trades/`
- `data/`: the same data as JSONL for agents and backtests
  - `filings.jsonl`: one filing per line (last {EXPORT_DAYS} days)
  - `trades.jsonl`: every paper trade
  - `universe.json`: today's universe
  - `scoreboard.json`: the bot's scoreboard and current rules (read by the BlackCrown admin)

## Rules for agents
- Read-only. Notes here are regenerated every {SYNC_MINUTES} minutes.
- Times are US Eastern unless a field ends in `_utc`.
- Paper results are simulated. Never present them as real returns or as a promise.
"""

    # ---- Universe ----
    rows = ["| Symbol | Name | Price | Mkt cap | Volume | Sector |", "|---|---|---:|---:|---:|---|"]
    for u in sorted(universe, key=lambda x: -(x["volume"] or 0)):
        rows.append(f"| {_tl(u['symbol'])} | {_cell(u['name'])} | ${u['price']:.2f} | "
                    f"${(u['mcap'] or 0)/1e9:.2f}B | {int(u['volume'] or 0):,} | {_cell(u['sector'])} |")
    asof = universe[0]["asof"] if universe else ""
    files["Universe.md"] = _fm(type="intel-universe", updated=_et_date(asof) or "n/a",
                               count=len(universe), tags=["korvus-intel"]) + \
        f"\n# Universe\n\n{GEN}\n{len(universe)} stocks, screened {_et(asof)} ET.\n\n" + "\n".join(rows) + "\n"

    # ---- daily filing notes (last FILING_DAYS days) ----
    cutoff = (now - dt.timedelta(days=FILING_DAYS)).isoformat()
    by_day = {}
    for f in filings:
        if f["seen_utc"] >= cutoff:
            by_day.setdefault(_et_date(f["seen_utc"]), []).append(f)
    for day, fs in by_day.items():
        out = [_fm(type="intel-filings", date=day, count=len(fs), tags=["korvus-intel", "filings"]),
               f"\n# Filings {day}\n\n{GEN}"]
        for f in sorted(fs, key=lambda x: x["seen_utc"]):
            lag = ""
            try:
                s = (dt.datetime.fromisoformat(f["seen_utc"]) - dt.datetime.fromisoformat(f["filed_utc"])).total_seconds()
                lag = f" (+{int(s)}s)" if 0 <= s < 3600 else ""
            except Exception:
                pass
            out.append(f"\n## {_tl(f['symbol'])} {_cell(f['headline'])}\n")
            out.append(f"- Form {f['form']} · items {', '.join(json.loads(f['items'] or '[]')) or 'n/a'}"
                       f" · filed {_et(f['filed_utc'], '%I:%M:%S %p')} ET · seen {_et(f['seen_utc'], '%I:%M:%S %p')} ET{lag}")
            if f.get("summary"):
                out.append(f"- **{(f['impact'] or '').upper()} · {f['direction']} · {f['confidence']}% · {f['catalyst']}**")
                out.append(f"- {f['summary']}")
                if f.get("read"):
                    out.append(f"- Read: {f['read']}")
            else:
                out.append("- Routine filing, not scored.")
            if f.get("ref_price"):
                out.append(f"- Price when seen: ${f['ref_price']:.2f} (prev close ${(f['prev_close'] or 0):.2f})")
            out.append(f"- [Open on SEC.gov]({f['url']})")
        files[f"Filings/{day}.md"] = "\n".join(out) + "\n"

    # ---- ticker notes ----
    tcut = (now - dt.timedelta(days=TICKER_DAYS)).isoformat()
    syms = {f["symbol"] for f in filings if f["seen_utc"] >= tcut} | {t["symbol"] for t in trades}
    uni = {u["symbol"]: u for u in universe}
    for s in sorted(syms):
        u = uni.get(s, {})
        out = [_fm(type="intel-ticker", symbol=s, sector=_cell(u.get("sector")) or "n/a",
                   tags=["korvus-intel", "ticker"]),
               f"\n# {s}{(' · ' + u['name']) if u.get('name') else ''}\n\n{GEN}"]
        if u:
            out.append(f"In today's universe at ${u['price']:.2f}, market cap ${(u['mcap'] or 0)/1e9:.2f}B.\n")
        fs = [f for f in filings if f["symbol"] == s and f["seen_utc"] >= tcut]
        if fs:
            out.append("## Filings\n")
            for f in fs:
                tag = f"{(f['impact'] or '').upper()} {f['direction']} {f['confidence']}%" if f.get("summary") else "routine"
                out.append(f"- {_et(f['seen_utc'], '%Y-%m-%d %I:%M %p')} · {f['form']} · {tag} · "
                           f"[[{SUBDIR}/Filings/{_et_date(f['seen_utc'])}|{_cell(f['headline'])[:90]}]]")
        ts = [t for t in trades if t["symbol"] == s]
        if ts:
            out.append("\n## Paper trades\n")
            for t in ts:
                res = (f"{t['exit_reason']} @ ${t['exit_px']:.2f}, {t['pnl_pct']:+.2f}%"
                       if t["status"] == "closed" else "open")
                out.append(f"- {_et(t['entry_utc'], '%Y-%m-%d %I:%M %p')} · {t['qty']} @ ${t['entry_px']:.2f} · {res}")
        files[f"Tickers/{s}.md"] = "\n".join(out) + "\n"

    # ---- Bot: strategy + scoreboard + ledgers ----
    files["Bot/Strategy.md"] = _fm(type="intel-strategy", version=bot.STRATEGY, tags=["korvus-intel", "paper-bot"]) + f"""
# Strategy {bot.STRATEGY}

{GEN}
**Paper only.** No broker connection, no real orders.

- **Trigger:** a universe filing scored bull, impact med or high, confidence at least {bot.MIN_CONF}%, seen in the last {bot.LOOKBACK_H:.0f} hours.
- **Confirm:** price above the reference price at the time the filing was seen, and up less than {bot.MAX_DAY_UP:.0f}% on the day.
- **Window:** entries 9:45 AM to 3:30 PM ET on regular sessions.
- **Size:** ${bot.NOTIONAL:,.0f} paper notional, at most {bot.MAX_OPEN} open, one entry per symbol per day.
- **Exit:** +{bot.TARGET_PCT}% target, -{bot.STOP_PCT}% stop, or flat at 3:55 PM ET.
- **Fills:** last quote with {bot.SLIP*100:.2f}% slippage, quotes polled every {bot.TICK_SECONDS}s. Real fills would be worse.

Changing any rule ships as a new version with a fresh [[{SUBDIR}/Bot/Scoreboard|Scoreboard]]; history is never rewritten.
"""
    wr = f"{sb['win_rate_pct']}%" if sb["win_rate_pct"] is not None else "n/a"
    sample = ("" if sb["sample_ok"] else
              f"\n> Sample too small to judge: {sb['closed_trades']} of {bot.MIN_SAMPLE} closed trades needed before the win rate means anything.\n")
    cats = "\n".join(f"| {c} | {v['trades']} | {round(100*v['wins']/v['trades'])}% |"
                     for c, v in sorted(sb["by_catalyst"].items())) or "| none yet | 0 | n/a |"
    files["Bot/Scoreboard.md"] = _fm(type="intel-scoreboard", version=bot.STRATEGY, updated=_et_date(data_asof) or "n/a",
                                     closed=sb["closed_trades"], tags=["korvus-intel", "paper-bot"]) + f"""
# Scoreboard · [[{SUBDIR}/Bot/Strategy|Strategy]] {bot.STRATEGY}

{GEN}
Data as of: {stamp}
{sample}
| Metric | Value |
|---|---|
| Closed trades | {sb['closed_trades']} |
| Open trades | {sb['open_trades']} |
| Win rate | {wr} |
| Avg win | {sb['avg_win_pct'] if sb['avg_win_pct'] is not None else 'n/a'}% |
| Avg loss | {sb['avg_loss_pct'] if sb['avg_loss_pct'] is not None else 'n/a'}% |
| Expectancy per trade | {sb['expectancy_pct'] if sb['expectancy_pct'] is not None else 'n/a'}% |
| Profit factor | {sb['profit_factor'] if sb['profit_factor'] is not None else 'n/a'} |
| Paper P&L | ${sb['paper_pnl']:,.2f} |
| Exits | {', '.join(f'{k} {v}' for k, v in sb['exits'].items()) or 'none yet'} |

## By catalyst
| Catalyst | Trades | Win rate |
|---|---:|---:|
{cats}

Paper results: simulated fills on 60-second quotes, no market impact. Not real returns.
"""
    by_month = {}
    for t in trades:
        by_month.setdefault(_et(t["entry_utc"], "%Y-%m"), []).append(t)
    for m, ts in by_month.items():
        rows = ["| Entry (ET) | Symbol | Qty | Entry | Exit | Reason | P&L | % |", "|---|---|---:|---:|---:|---|---:|---:|"]
        for t in sorted(ts, key=lambda x: x["entry_utc"]):
            if t["status"] == "closed":
                rows.append(f"| {_et(t['entry_utc'], '%m-%d %I:%M %p')} | {_tl(t['symbol'])} | {t['qty']} | "
                            f"{t['entry_px']:.2f} | {t['exit_px']:.2f} | {t['exit_reason']} | {t['pnl']:+.2f} | {t['pnl_pct']:+.2f} |")
            else:
                rows.append(f"| {_et(t['entry_utc'], '%m-%d %I:%M %p')} | {_tl(t['symbol'])} | {t['qty']} | "
                            f"{t['entry_px']:.2f} | open | | | |")
        files[f"Bot/Trades/{m}.md"] = _fm(type="intel-ledger", month=m, tags=["korvus-intel", "paper-bot"]) + \
            f"\n# Paper trades {m}\n\n{GEN}\n" + "\n".join(rows) + "\n"

    # ---- machine-readable ----
    keep = ("accession", "symbol", "company", "form", "items", "filed_utc", "seen_utc", "url", "headline",
            "ref_price", "prev_close", "summary", "read", "catalyst", "impact", "direction", "confidence",
            "scorer")
    files["data/filings.jsonl"] = "".join(
        json.dumps({k: (json.loads(f[k] or "[]") if k == "items" else f.get(k)) for k in keep}) + "\n"
        for f in sorted(filings, key=lambda x: x["seen_utc"]))
    files["data/trades.jsonl"] = "".join(json.dumps(t) + "\n" for t in sorted(trades, key=lambda x: x["entry_utc"]))
    files["data/universe.json"] = json.dumps(universe, indent=1) + "\n"
    files["data/scoreboard.json"] = json.dumps({
        "data_asof_utc": data_asof,
        "scoreboard": sb,
        "min_sample": bot.MIN_SAMPLE,
        "universe_count": len(universe),
        "universe_asof": asof,
        "rules": {"strategy": bot.STRATEGY, "notional": bot.NOTIONAL, "max_open": bot.MAX_OPEN,
                  "target_pct": bot.TARGET_PCT, "stop_pct": bot.STOP_PCT, "min_confidence": bot.MIN_CONF,
                  "max_day_up_pct": bot.MAX_DAY_UP, "lookback_hours": bot.LOOKBACK_H,
                  "slippage_pct": round(bot.SLIP * 100, 3), "tick_seconds": bot.TICK_SECONDS,
                  "price_band": [intel.PRICE_MIN, intel.PRICE_MAX], "mcap_max": intel.MCAP_MAX},
    }, indent=1) + "\n"
    return files


# ----------------------------------------------------------------------------
# git
# ----------------------------------------------------------------------------
def _git(args: list, cwd: str = None, check: bool = True) -> subprocess.CompletedProcess:
    pre = ["git", "-c", f"user.name={AUTHOR.split('<')[0].strip()}",
           "-c", f"user.email={AUTHOR.split('<')[-1].rstrip('>').strip()}"]
    if TOKEN and REPO_URL.startswith("https://"):
        basic = base64.b64encode(f"x-access-token:{TOKEN}".encode()).decode()
        pre += ["-c", f"http.extraHeader=Authorization: Basic {basic}"]
    r = subprocess.run(pre + args, cwd=cwd, capture_output=True, text=True, timeout=180)
    if check and r.returncode != 0:
        msg = (r.stderr or r.stdout).replace(TOKEN, "***") if TOKEN else (r.stderr or r.stdout)
        raise RuntimeError(f"git {args[0]} failed: {msg.strip()[:400]}")
    return r


def _ensure_clone():
    if os.path.isdir(os.path.join(VAULT_DIR, ".git")):
        return
    os.makedirs(os.path.dirname(VAULT_DIR) or ".", exist_ok=True)
    _git(["clone", "--depth", "50", REPO_URL, VAULT_DIR])


def write_files(files: dict, root: str) -> int:
    """Write rendered files under root/SUBDIR; remove stale generated notes in
    Filings/Tickers that are no longer rendered is NOT done (history stays)."""
    changed = 0
    for rel, text in files.items():
        p = os.path.join(root, SUBDIR, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        old = None
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                old = f.read()
        if old != text:
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            changed += 1
    return changed


def sync(render_only: bool = False) -> dict:
    files = render()
    if render_only:
        n = write_files(files, VAULT_DIR)
        return {"rendered": len(files), "changed": n, "pushed": False}
    _ensure_clone()
    _git(["fetch", "--depth", "50", "origin"], cwd=VAULT_DIR)
    branch = _git(["rev-parse", "--abbrev-ref", "HEAD"], cwd=VAULT_DIR).stdout.strip() or "main"
    _git(["reset", "--hard", f"origin/{branch}"], cwd=VAULT_DIR)   # our clone holds no local work
    n = write_files(files, VAULT_DIR)
    _git(["add", "--", SUBDIR], cwd=VAULT_DIR)
    if not _git(["status", "--porcelain", "--", SUBDIR], cwd=VAULT_DIR).stdout.strip():
        return {"rendered": len(files), "changed": 0, "pushed": False}
    _git(["commit", "-m", f"Korvus Intel sync {intel.utcnow().strftime('%Y-%m-%dT%H:%M')}"], cwd=VAULT_DIR)
    for attempt in (1, 2, 3):
        r = _git(["push", "origin", f"HEAD:{branch}"], cwd=VAULT_DIR, check=False)
        if r.returncode == 0:
            print(f"  [vault] pushed {n} changed note(s) to {SUBDIR}/")
            return {"rendered": len(files), "changed": n, "pushed": True}
        # someone (the agents' brain sync) pushed first: replay ours on top
        _git(["pull", "--rebase", "origin", branch], cwd=VAULT_DIR, check=False)
    raise RuntimeError("vault push rejected 3 times")


def main():
    ap = argparse.ArgumentParser(description="Render Korvus Intel into the Obsidian vault repo")
    ap.add_argument("--render-only", action="store_true")
    a = ap.parse_args()
    intel.db_init()
    print(json.dumps(sync(render_only=a.render_only)))


if __name__ == "__main__":
    main()
