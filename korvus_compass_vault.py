"""
Korvus Compass -> Obsidian vault (the `compass/` folder of blackcrown-brain).

Pure render: korvus_compass.db -> {relative_path: markdown}. Korvus Intel's
vault sync (korvus_vault.sync) is the single git writer for the brain repo; it
calls render() here and publishes both crawlers' notes in one commit, so the
two never fight over the clone. Notes cross-link: a Compass stock note links
to the Intel ticker note when Intel also follows that stock, and the reverse.

Notes are stamped with when the DATA changed, never the render time, so an idle
sync writes nothing.
"""

import os
import json
import sqlite3
import datetime as dt

import korvus_compass as c

SUBDIR = c._env("VAULT_COMPASS_SUBDIR", "compass").strip("/")
INTEL_SUBDIR = c._env("VAULT_SUBDIR", "intel").strip("/")
GEN = "> Generated by Korvus Compass. Do not edit by hand; the next sync overwrites this note.\n"
READ = {"bull": "Bullish", "bear": "Bearish", "neut": "Neutral"}


def _cell(t) -> str:
    return str(t or "").replace("|", "/").replace("\n", " ").strip()


def _fm(**kv) -> str:
    out = ["---"]
    for k, v in kv.items():
        out.append(f"{k}: [{', '.join(v)}]" if isinstance(v, list) else f"{k}: {json.dumps(v) if isinstance(v, str) else v}")
    return "\n".join(out) + "\n---\n"


def _sl(sym: str) -> str:
    return f"[[{SUBDIR}/Stocks/{sym}|{sym}]]"


def lookup() -> dict:
    """{SYM: {tier, read, score, trend}} for other crawlers' notes. Safe when
    the Compass database does not exist yet."""
    conn = c._ro()
    if not conn:
        return {}
    try:
        rows = conn.execute("""SELECT symbol, tier, read, score, trend FROM stocks WHERE active=1
                               AND COALESCE(kind,'stock')='stock' AND score IS NOT NULL""").fetchall()
        return {r["symbol"]: dict(r) for r in rows}
    except Exception:
        return {}
    finally:
        conn.close()


def _intel_symbols() -> set:
    if not os.path.exists(c.INTEL_DB):
        return set()
    try:
        k = sqlite3.connect(f"file:{c.INTEL_DB}?mode=ro", uri=True, timeout=5)
        out = {r[0] for r in k.execute("SELECT DISTINCT symbol FROM filings")}
        k.close()
        return out
    except Exception:
        return set()


def render() -> dict:
    conn = c._ro()
    if not conn:
        return {}
    rows = [c.row_to_dict(r) for r in conn.execute("SELECT * FROM stocks WHERE active=1")]
    events = [dict(r) for r in conn.execute("SELECT * FROM events ORDER BY ts_utc DESC, id DESC LIMIT 80")]
    conn.close()
    stocks = [s for s in rows if s.get("kind") != "etf"]
    funds = [s for s in rows if s.get("kind") == "etf"]
    scored = sorted([s for s in stocks if s.get("score") is not None and s.get("tier") != "Building"],
                    key=lambda s: -s["score"])
    if not scored and not events:
        return {}
    asof = max([s["price_date"] for s in rows if s.get("price_date")] or [""])
    intel = _intel_symbols()
    files = {}
    n = lambda k: sum(1 for s in scored if s.get("read") == k)

    files["README.md"] = _fm(type="compass-index", updated=asof or "n/a", tags=["korvus-compass"]) + f"""
# Korvus Compass

The second Korvus crawler. It follows every S&P 500 and Nasdaq-100 company for long-term
investors: price trend, the financials each company reports to the SEC, analyst consensus,
and a 0 to 100 Compass score. An analyst agent writes a plain-English brief for every stock.

{GEN}
Prices as of: {asof or 'no data yet'} close · {len(scored)} of {len(stocks)} stocks scored ·
{n('bull')} bullish, {n('neut')} neutral, {n('bear')} bearish reads

## Where things are
- [[{SUBDIR}/Board|Board]]: the ranked board, top and bottom of the list, and the index funds
- [[{SUBDIR}/Updates|Updates]]: what the crawler saw change (filings, new quarters, trend turns, tier moves)
- `Stocks/SYMBOL.md`: one note per stock with the analyst brief and key numbers
- `data/board.json`: the whole board as JSON for agents

## How the two crawlers work together
- [[{INTEL_SUBDIR}/README|Korvus Intel]] reads SEC filings for small stocks the moment they land and runs the paper bot.
- Compass reads Intel's filing reads (and the terminal's) for any stock on this board and folds them into
  the score and the brief. Intel's ticker notes show the Compass rating when a stock is on both.
- They share one SEC request budget and one vault. Intel's sync publishes both folders in a single commit.

## Rules for agents
- Read-only. Notes here are regenerated by the sync.
- Scores are research summaries of public data, not predictions and not advice. Never present a
  Compass score or read as a recommendation to buy or sell.
"""

    def table(items):
        out = ["| # | Stock | Name | Score | Tier | Read | Trend | 1 year |", "|---:|---|---|---:|---|---|---|---:|"]
        for i, s in items:
            out.append(f"| {i} | {_sl(s['symbol'])} | {_cell(s['name'])} | {round(s['score'])} | {s['tier']} | "
                       f"{READ.get(s['read'], 'Neutral')} | {_cell(s['trend'])} | {c.pct(s.get('ret_1y'))} |")
        return "\n".join(out)

    top = list(enumerate(scored[:40], 1))
    bottom = [(len(scored) - i, s) for i, s in enumerate(reversed(scored[-20:]))] if len(scored) > 60 else []
    board = [_fm(type="compass-board", updated=asof or "n/a", tags=["korvus-compass"]),
             f"\n# Compass board\n\n{GEN}\nPrices as of {asof or 'n/a'} close.\n\n## Highest scores\n\n" + table(top)]
    if bottom:
        board.append("\n## Lowest scores\n\n" + table(bottom))
    if funds:
        board.append("\n## Index funds (trend only, not scored)\n\n| Fund | Tracks | Trend | 1 year | 5 years |\n|---|---|---|---:|---:|")
        for s in funds:
            board.append(f"| {s['symbol']} | {_cell(s['name'])} | {_cell(s['trend'])} | {c.pct(s.get('ret_1y'))} | {c.pct(s.get('ret_5y'))} |")
    files["Board.md"] = "\n".join(board) + "\n"

    up = [_fm(type="compass-updates", updated=(events[0]["ts_utc"][:10] if events else "n/a"), tags=["korvus-compass"]),
          f"\n# Compass updates\n\n{GEN}"]
    for e in events:
        up.append(f"- {e['ts_utc'][:16].replace('T', ' ')} UTC · {_sl(e['symbol'])} · **{_cell(e['title'])}**"
                  + (f" · {_cell(e['detail'])}" if e.get("detail") else ""))
    files["Updates.md"] = "\n".join(up) + "\n"

    for s in stocks:
        b = s.get("brief") or {}
        if not b.get("headline"):
            continue
        f = s.get("fund") or {}
        cur = f.get("currency", "USD")
        sym = s["symbol"]
        out = [_fm(type="compass-stock", symbol=sym, tier=s.get("tier") or "Building",
                   read=READ.get(s.get("read"), "Neutral"), sector=_cell(s.get("sector")) or "n/a",
                   tags=["korvus-compass", "stock"]),
               f"\n# {sym} · {_cell(s.get('name'))}\n\n{GEN}",
               f"**{s.get('tier')}** · {READ.get(s.get('read'), 'Neutral')} read · trend: {_cell(s.get('trend'))}\n",
               f"## {_cell(b['headline'])}\n", _cell(b.get("summary")), ""]
        if b.get("bull"):
            out += ["### What is working"] + [f"- {_cell(x)}" for x in b["bull"]] + [""]
        if b.get("bear"):
            out += ["### What to be careful about"] + [f"- {_cell(x)}" for x in b["bear"]] + [""]
        if b.get("watch"):
            out += [f"**Watch next:** {_cell(b['watch'])}", ""]
        if b.get("fit"):
            out += [f"**Tends to suit:** {_cell(b['fit'])}", ""]
        who = {"haiku": "the Compass Analyst (Claude Haiku)", "crown": "the Compass Analyst (Crown)"}.get(b.get("by"), "Compass rules")
        out += [f"Written by {who} on {str(b.get('at') or '')[:10]}. Research, not advice.", ""]
        if f.get("revenue") is not None:
            out += [f"## Key numbers (fiscal year ended {f.get('fy_end')})",
                    f"- Revenue {c.money(f.get('revenue'), cur)} ({c.pct(f.get('revenue_yoy'))} vs prior year)",
                    f"- Net margin {c.pct(f.get('net_margin'), 0, False)}, free cash flow {c.money(f.get('fcf'), cur)}",
                    f"- Cash {c.money(f.get('cash'), cur)}, debt {c.money(f.get('debt'), cur)}", ""]
        if sym in intel:
            out += [f"Also followed by Korvus Intel: [[{INTEL_SUBDIR}/Tickers/{sym}|{sym} filings and paper trades]]", ""]
        files[f"Stocks/{sym}.md"] = "\n".join(out)

    val = lambda s: c.valuation(s)
    files["data/board.json"] = json.dumps({
        "price_asof": asof,
        "stocks": [{"symbol": s["symbol"], "name": s["name"], "sector": s["sector"], "score": s["score"],
                    "tier": s["tier"], "read": s["read"], "trend": s["trend"], "ret_1y": s.get("ret_1y"),
                    "pe": val(s)["pe"], "div_yield": val(s)["div_yield"],
                    "headline": (s.get("brief") or {}).get("headline")} for s in scored],
        "funds": [{"symbol": s["symbol"], "tracks": s["name"], "trend": s["trend"], "ret_1y": s.get("ret_1y")} for s in funds],
    }, indent=1) + "\n"
    return files
